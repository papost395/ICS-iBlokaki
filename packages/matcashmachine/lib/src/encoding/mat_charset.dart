/// Character encoding support for the MAT fiscal protocol.
///
/// MAT ECR devices for the Greek market use the **Windows-1253 (CP1253)** code page.
/// This module provides encoding and decoding between Dart Strings (UTF-16)
/// and the byte sequences expected by the ECR over TCP.
library;

import '../exceptions.dart';

// ── Public API ────────────────────────────────────────────────────────────────

/// The character encoding used when serialising text fields to ECR wire bytes.
///
/// Choose based on the language configuration of your ECR device.
enum MatCharset {
  /// Standard 7-bit ASCII.
  ///
  /// Only supports characters U+0000–U+007F. Use only if your ECR
  /// is configured for a non-Greek locale.
  ascii,

  /// Windows Code Page 1253 (Greek) — **default for Greek fiscal ECRs**.
  ///
  /// Supports all modern Greek characters (with accents), the euro sign (€),
  /// and standard Latin/punctuation. This is the standard encoding for
  /// MIRKA III and INFOCARINA i57 III devices sold in Greece.
  windows1253,
}

/// Encodes a Dart [String] to bytes using [charset].
///
/// Throws [MatPacketException] if [s] contains characters that cannot be
/// represented in the specified encoding.
List<int> encodeString(String s, MatCharset charset) {
  switch (charset) {
    case MatCharset.ascii:
      return _encodeAscii(s);
    case MatCharset.windows1253:
      return _encodeWindows1253(s);
  }
}

/// Decodes bytes produced by [encodeString] back to a Dart [String].
///
/// Bytes that are undefined in the codec are replaced with the Unicode
/// replacement character (U+FFFD).
String decodeBytes(List<int> bytes, MatCharset charset) {
  switch (charset) {
    case MatCharset.ascii:
      return String.fromCharCodes(bytes.where((b) => b < 0x80));
    case MatCharset.windows1253:
      return _decodeWindows1253(bytes);
  }
}

// ── ASCII implementation ──────────────────────────────────────────────────────

List<int> _encodeAscii(String s) {
  final result = <int>[];
  for (final cu in s.codeUnits) {
    if (cu > 0x7F) {
      throw MatPacketException(
        'ASCII encoding: character "${String.fromCharCode(cu)}" '
        '(U+${cu.toRadixString(16).padLeft(4, "0").toUpperCase()}) '
        'is not representable in ASCII. '
        'Use MatCharset.windows1253 to send Greek text.',
      );
    }
    result.add(cu);
  }
  return result;
}

// ── Windows-1253 implementation ───────────────────────────────────────────────

List<int> _encodeWindows1253(String s) {
  final result = <int>[];
  for (final cu in s.codeUnits) {
    if (cu < 0x80) {
      // 0x00–0x7F identical to ASCII / Unicode.
      result.add(cu);
    } else {
      final byte = _unicodeToWin1253[cu];
      if (byte == null) {
        throw MatPacketException(
          'Windows-1253 encoding: character "${String.fromCharCode(cu)}" '
          '(U+${cu.toRadixString(16).padLeft(4, "0").toUpperCase()}) '
          'cannot be represented in Windows-1253. '
          'Remove or transliterate the character.',
        );
      }
      result.add(byte);
    }
  }
  return result;
}

String _decodeWindows1253(List<int> bytes) {
  final buf = StringBuffer();
  for (final byte in bytes) {
    if (byte < 0x80) {
      buf.writeCharCode(byte);
    } else {
      buf.writeCharCode(_win1253ToUnicode[byte] ?? 0xFFFD);
    }
  }
  return buf.toString();
}

